COMMENT ON COLUMN auth_requests.device_code IS 'Random UUID generated by MCP client - binds client to auth session';
COMMENT ON COLUMN auth_requests.session_token_hash IS 'SHA-256 hash of session token - plain token only sent once';
COMMENT ON COLUMN session_tokens.token_hash IS 'SHA-256 hash for validation - plain token never stored';
